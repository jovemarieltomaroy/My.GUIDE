export async function createAccomplishmentWorkbook({ report, period, coverage, filters, generatedBy, generatedAt }) {
  const { default: ExcelJS } = await import('exceljs');
  const workbook = new ExcelJS.Workbook();
  workbook.creator = 'My.GUIDE';
  const sheet = workbook.addWorksheet('OPCR Accomplishment', {
    views: [{ state: 'frozen', ySplit: 9 }],
    pageSetup: { paperSize: 9, orientation: 'landscape', fitToPage: true, fitToWidth: 1, fitToHeight: 0 },
  });
  sheet.columns = [{ width: 6 }, { width: 60 }, { width: 19 }, { width: 17 }, { width: 20 }, { width: 85 }];
  const mergedRow = (text, fill, bold = false) => {
    const row = sheet.addRow([text]);
    sheet.mergeCells(row.number, 1, row.number, 6);
    row.font = { name: 'Arial', size: bold ? 14 : 10, bold };
    row.alignment = { vertical: 'middle', wrapText: true };
    row.height = bold ? 28 : 30;
    if (fill) row.getCell(1).fill = { type: 'pattern', pattern: 'solid', fgColor: { argb: fill } };
    return row;
  };
  mergedRow('Office of Guidance & Counseling', 'FFFFFF00', true);
  mergedRow(`OPCR ACCOMPLISHMENT — ${period}`, 'FFFFFF00', true);
  mergedRow('Whole-number counts and percentages from My.GUIDE records', 'FFFFFF00');
  mergedRow(`Coverage: ${coverage}`);
  mergedRow(`Filters: ${filters}`);
  mergedRow(`Generated by: ${generatedBy} | ${generatedAt}`);
  mergedRow('CONFIDENTIAL — For authorized institutional use only');
  sheet.addRow([]);
  const header = sheet.addRow(['No.', 'Indicator', 'Target', 'Actual count', 'Actual percentage', 'Remarks / calculation basis']);
  header.height = 30;
  header.font = { name: 'Arial', size: 11, bold: true };
  header.alignment = { vertical: 'middle', wrapText: true };
  header.eachCell(cell => { cell.fill = { type: 'pattern', pattern: 'solid', fgColor: { argb: 'FFE9E9E9' } }; });

  let group;
  for (const item of report.rows) {
    if (group !== item.Group) {
      group = item.Group;
      mergedRow(group, 'FFFFF2CC', true);
    }
    const percent = item['Actual percentage'];
    const numericPercent = /^\d+(\.\d+)?%$/.test(percent);
    const row = sheet.addRow([item.No, item.Indicator, item.Target, item['Actual count'], numericPercent ? Number.parseFloat(percent) / 100 : percent, item.Remarks]);
    row.font = { name: 'Arial', size: 11 };
    row.alignment = { vertical: 'top', wrapText: true };
    row.height = Math.max(42, Math.ceil(item.Remarks.length / 78) * 16 + 12, Math.ceil(item.Indicator.length / 53) * 16 + 12);
    row.getCell(1).font = { name: 'Arial', size: 12, bold: true, color: { argb: 'FF8C1518' } };
    row.getCell(4).alignment = { vertical: 'top', horizontal: 'center', wrapText: true };
    row.getCell(5).alignment = { vertical: 'top', horizontal: 'center', wrapText: true };
    if (numericPercent) row.getCell(5).numFmt = '0.0%';
    for (const column of [4, 5]) {
      if (row.getCell(column).value === 'Not tracked') row.getCell(column).font = { name: 'Arial', size: 11, italic: true, color: { argb: 'FF777777' } };
    }
  }
  sheet.eachRow({ includeEmpty: false }, row => {
    for (let column = 1; column <= 6; column++) row.getCell(column).border = {
      bottom: { style: 'thin', color: { argb: 'FFD9D9D9' } },
      right: { style: 'thin', color: { argb: 'FFD9D9D9' } },
    };
  });
  mergedRow('Calculation notes', 'FFFFF2CC', true);
  report.notes.forEach(note => mergedRow(note));
  sheet.pageSetup.printTitlesRow = '1:9';
  sheet.pageSetup.printArea = `A1:F${sheet.rowCount}`;
  sheet.headerFooter.oddFooter = '&LMy.GUIDE — Confidential&RPage &P of &N';
  return workbook;
}
